export type Strings = typeof STRINGS.en;

function initialLang(): Lang {
  const q = new URLSearchParams(window.location.search).get("lang");
  if (q === "zh" || q === "en") return q;
  try {
    const saved = localStorage.getItem("lab-lang");
    if (saved === "zh" || saved === "en") return saved;
  } catch { /* storage may be blocked */ }
  return navigator.language?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

const Ctx = createContext<{ lang: Lang; t: Strings; setLang: (l: Lang) => void }>({
  lang: "en", t: STRINGS.en, setLang: () => {},
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    document.title = lang === "zh" ? "Investment Lab · 投资实验室" : "Investment Lab";
  }, [lang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem("lab-lang", l); } catch { /* ignore */ }
    const url = new URL(window.location.href);
    url.searchParams.set("lang", l);
    window.history.replaceState({}, "", url.pathname + url.search);
  };
  return <Ctx.Provider value={{ lang, t: STRINGS[lang] as Strings, setLang }}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);
